import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'America/Sao_Paulo' })
const key = 'orlando-guide:/orlando-test/:progress:v1'
test.beforeEach(async ({ page }) => { await page.clock.setFixedTime(new Date('2026-10-22T15:00:00Z')) })

test('home oferece três áreas e os quatro dias abrem os roteiros sem duplicar atrações', async ({ page }) => {
  await page.goto('./')
  await expect(page.locator('.travel-entry')).toContainText('Roteiro da Viagem')
  await expect(page.locator('.parks-entry')).toContainText('Meus Parques')
  await expect(page.locator('.checklist-entry')).toContainText('Checklist geral de preparação')
  await page.locator('.travel-entry').click()
  await expect(page).toHaveURL(/#\/viagem\/2026-10-27$/)
  await expect(page.locator('.trip-date')).toHaveCount(14)
  const days = [['2026-10-30', 'islands-of-adventure', 'step-velocicoaster'], ['2026-11-01', 'magic-kingdom', 'step-big-thunder'], ['2026-11-03', 'universal-studios', 'step-gringotts'], ['2026-11-05', 'epic-universe', 'step-mario-kart']]
  for (const [date, park, step] of days) {
    await page.goto(`./#/viagem/${date}`)
    await expect(page.locator('.step-card')).toHaveCount(0)
    await page.locator('.activity-park-link').click()
    await expect(page).toHaveURL(new RegExp(`#/parque/${park}$`))
    await expect(page.getByTestId(step)).toBeAttached()
    await page.getByRole('link', { name: 'Voltar ao Roteiro da Viagem' }).click()
    await expect(page).toHaveURL(new RegExp(`#/viagem/${date}$`))
  }
  await page.getByRole('button', { name: 'Próximo dia', exact: true }).click()
  await expect(page.locator('#trip-day-title')).toHaveText('Viagem para Miami')
  await page.getByRole('button', { name: 'Dia anterior', exact: true }).click()
  await expect(page.locator('#trip-day-title')).toHaveText('Epic Universe e Port Orleans')
})

test('atividades originais: progresso independente, edição, ocultar, restaurar e recarregar', async ({ page }) => {
  await page.goto('./#/parque/magic-kingdom')
  const before = await page.evaluate(storageKey => localStorage.getItem(storageKey), key)
  await page.goto('./#/viagem/2026-11-01')
  const activity = page.getByTestId('activity-visit-magic')
  await activity.getByRole('button', { name: /^Concluir atividade:/ }).click()
  await expect(page.getByRole('progressbar', { name: 'Progresso do dia' })).toHaveAttribute('aria-valuenow', '50')
  await activity.getByRole('button', { name: /^Expandir atividade:/ }).click()
  await activity.getByRole('button', { name: 'Editar atividade', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Nosso dia no Magic')
  await page.getByLabel('Observações pessoais (opcional)').fill('Encontro do grupo na entrada.')
  await page.getByRole('button', { name: 'Salvar atividade', exact: true }).click()
  await page.reload()
  await expect(activity).toContainText('Nosso dia no Magic')
  await activity.getByRole('button', { name: /^Expandir atividade:/ }).click()
  await expect(activity).toContainText('Encontro do grupo na entrada.')
  await activity.getByRole('button', { name: 'Ocultar atividade', exact: true }).click()
  await expect(activity).toHaveCount(0)
  await page.locator('.trip-hidden summary').click()
  await page.getByRole('button', { name: 'Restaurar Visitar Magic Kingdom', exact: true }).click()
  await expect(activity).toContainText('Nosso dia no Magic')
  await activity.getByRole('button', { name: /^Expandir atividade:/ }).click()
  await activity.getByRole('button', { name: 'Restaurar texto original' }).click()
  await expect(activity).toContainText('Visitar Magic Kingdom')
  await expect(activity).toHaveClass(/activity-completed/)
  const after = await page.evaluate(storageKey => JSON.parse(localStorage.getItem(storageKey)!), key)
  const old = before ? JSON.parse(before) : null
  if (old) { expect(after.parks).toEqual(old.parks); expect(after.globalChecklist).toEqual(old.globalChecklist); expect(after.extraGoals).toEqual(old.extraGoals) }
  expect(Object.values(after.parks['magic-kingdom'].statuses).every(status => status === 'pending')).toBe(true)
})

test('adiciona, edita, reordena e exclui atividade personalizada com desfazer', async ({ page }) => {
  await page.goto('./#/viagem/2026-10-29')
  await page.getByRole('button', { name: 'Adicionar atividade', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Café do grupo')
  await page.getByLabel('Horário local (opcional)').fill('08:15')
  await page.getByLabel('Categoria', { exact: true }).selectOption('food')
  await page.getByLabel('Localização (opcional)').fill('Perto da hospedagem')
  await page.getByLabel('Descrição (opcional)').fill('Escolher na hora.')
  await page.getByLabel('Observações pessoais (opcional)').fill('Ponto de encontro: recepção.')
  await page.getByRole('button', { name: 'Salvar atividade', exact: true }).click()
  const custom = page.locator('.trip-activity').filter({ hasText: 'Café do grupo' })
  await expect(page.locator('.trip-activity').last()).toContainText('Café do grupo')
  await expect(custom).toContainText('08h15')
  await page.getByRole('button', { name: 'Reordenar atividades', exact: true }).click()
  await custom.getByRole('button', { name: /para cima/ }).click()
  await expect(page.locator('.trip-activity').nth(2)).toContainText('Café do grupo')
  await custom.getByRole('button', { name: /^Expandir atividade:/ }).click()
  await custom.getByRole('button', { name: 'Editar atividade', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Café antes das compras')
  await page.getByRole('button', { name: 'Salvar atividade', exact: true }).click()
  await page.reload()
  const edited = page.locator('.trip-activity').filter({ hasText: 'Café antes das compras' })
  await expect(page.locator('.trip-activity').nth(2)).toContainText('Café antes das compras')
  await edited.getByRole('button', { name: /^Pular atividade:/ }).click()
  await expect(edited).toHaveClass(/activity-skipped/)
  await edited.getByRole('button', { name: /^Expandir atividade:/ }).click()
  await edited.getByRole('button', { name: 'Excluir atividade', exact: true }).click()
  await expect(edited).toHaveCount(0)
  await page.locator('.toast').getByRole('button', { name: 'Desfazer', exact: true }).click()
  await expect(edited).toHaveClass(/activity-skipped/)
})

