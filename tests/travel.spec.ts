test('migração, backup e offline preservam agenda e dados antigos', async ({ page, context }) => {
  await page.goto('./#/parque/islands-of-adventure')
  await page.getByTestId('step-hagrids').getByRole('button', { name: /^Voltar depois:/ }).click()
  await page.evaluate(storageKey => {
    const state = JSON.parse(localStorage.getItem(storageKey)!)
    delete state.trip
    state.globalChecklist.checked.tickets = true
    localStorage.setItem(storageKey, JSON.stringify(state))
  }, key)
  await page.reload()
  await page.goto('./#/viagem/2026-11-03')
  const visit = page.getByTestId('activity-visit-studios')
  await visit.getByRole('button', { name: /^Concluir atividade:/ }).click()
  await expect(page.getByRole('progressbar', { name: 'Progresso do dia' })).toHaveAttribute('aria-valuenow', '50')
  await expect(page.getByTestId('activity-try-hogwarts')).toContainText('Opcional')
  await page.getByTestId('activity-citywalk').getByRole('button', { name: /^Concluir atividade:/ }).click()
  await expect(page.getByRole('progressbar', { name: 'Progresso do dia' })).toHaveAttribute('aria-valuenow', '100')
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('button', { name: 'Ferramentas', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar roteiro e progresso' }).click()
  const path = await (await download).path()
  await page.getByRole('button', { name: 'Fechar ferramentas', exact: true }).click()
  await visit.getByRole('button', { name: /^Desmarcar atividade:/ }).click()
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('button', { name: 'Ferramentas', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles(path!)
  await expect(visit).toHaveClass(/activity-completed/)
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await expect(page.locator('.connection')).toContainText('Pronto para usar offline', { timeout: 20000 })
  await page.reload()
  await context.setOffline(true)
  await page.reload()
  await expect(visit).toHaveClass(/activity-completed/)
  await page.getByTestId('activity-try-hogwarts').getByRole('button', { name: /^Pular atividade:/ }).click()
  await page.reload()
  await expect(page.getByTestId('activity-try-hogwarts')).toHaveClass(/activity-skipped/)
  await page.locator('.activity-park-link').click()
  await expect(page.getByTestId('step-gringotts')).toHaveClass(/status-pending/)
  const state = await page.evaluate(storageKey => JSON.parse(localStorage.getItem(storageKey)!), key)
  expect(state.parks['islands-of-adventure'].statuses.hagrids).toBe('later')
  expect(state.globalChecklist.checked.tickets).toBe(true)
  expect(state.extraGoals['universal-studios']['hogwarts-express-hogsmeade']).toBe('pending')
})

test('agenda responsiva nos dois temas e editor confortável no celular', async ({ page }) => {
  test.setTimeout(60_000)
  for (const theme of ['dark', 'light']) {
    await page.goto('./')
    if (theme === 'light') await page.getByRole('button', { name: 'Ativar modo claro' }).click()
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      for (const [name, path] of [['home', './'], ['day', './#/viagem/2026-10-28'], ['game', './#/viagem/2026-11-07']]) {
        await page.goto(path)
        await expect(page.locator('body')).toHaveJSProperty('scrollWidth', width)
        if (width === 390 || width === 1440) {
          if (name === 'home') await page.locator('.travel-entry').scrollIntoViewIfNeeded()
          else await page.locator('.trip-day-header').scrollIntoViewIfNeeded()
          await page.screenshot({ path: `test-results/travel-${name}-${theme}-${width}.png` })
        }
      }
    }
    await page.setViewportSize({ width: 390, height: 900 })
    await page.getByRole('button', { name: 'Adicionar atividade', exact: true }).click()
    await expect(page.locator('dialog[open]')).toBeVisible()
    await page.screenshot({ path: `test-results/travel-editor-${theme}.png` })
    await page.getByRole('button', { name: 'Fechar edição de atividade', exact: true }).click()
  }
})
