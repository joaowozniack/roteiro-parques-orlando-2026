import { expect, test } from '@playwright/test'

test('destaque muda na virada do dia em Orlando sem recarregar e conserva as pendências', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-31T03:59:00Z') }) // 30/10, 23h59 em Orlando
  await page.goto('./')
  await expect(page.locator('.featured-park h2')).toContainText('Islands of')
  await page.locator('.featured-park').click()
  await page.getByTestId('step-arrival').getByRole('button', { name: /^Concluir / }).click()
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('link', { name: 'Viagem', exact: true }).click()
  await page.clock.fastForward(61_000)
  await expect(page.locator('.featured-park h2')).toHaveText('Magic Kingdom')
  await expect(page.locator('.featured-park')).toHaveAttribute('href', '#/parque/magic-kingdom')
  await expect(page.locator('.featured-date strong')).toHaveText('01 NOV')
  await expect(page.locator('.sidebar-trip strong')).toHaveText('Magic Kingdom')
  const islandsCard = page.locator('.upcoming-park').filter({ hasText: 'Islands of Adventure' })
  await expect(islandsCard).toContainText('9% concluído')
  await islandsCard.getByRole('link', { name: 'Islands of Adventure', exact: true }).click()
  await expect(page.getByTestId('step-arrival')).toHaveClass(/status-completed/)
})

test('100% adianta o destaque, desfazer recupera o anterior e recarregar preserva a escolha', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-20T12:00:00Z'))
  await page.goto('./#/parque/islands-of-adventure')
  const cards = page.locator('.step-card')
  const count = await cards.count()
  for (let index = 0; index < count - 1; index++) await cards.nth(index).getByRole('button', { name: /^Concluir / }).click()
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('link', { name: 'Viagem', exact: true }).click()
  await expect(page.locator('.featured-park h2')).toContainText('Islands of')
  await page.locator('.featured-park').click()
  await cards.last().getByRole('button', { name: /^Concluir / }).click()
  await expect(page).toHaveURL(/#\/parque\/islands-of-adventure$/)
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('link', { name: 'Viagem', exact: true }).click()
  await expect(page.locator('.featured-park h2')).toHaveText('Magic Kingdom')
  await expect(page.locator('.featured-step-count')).toContainText('0% concluído')
  await page.locator('.toast').getByRole('button', { name: 'Desfazer', exact: true }).click()
  await expect(page.locator('.featured-park h2')).toContainText('Islands of')
  await page.locator('.featured-park').click()
  await cards.last().getByRole('button', { name: /^Concluir / }).click()
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('link', { name: 'Viagem', exact: true }).click()
  await page.reload()
  await expect(page.locator('.featured-park h2')).toHaveText('Magic Kingdom')
  await expect(page.locator('.upcoming-park').filter({ hasText: 'Islands of Adventure' })).toContainText('100% concluído')
})

test('Magic aparece no destaque em 01/11, com conteúdo dinâmico e layout móvel', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-01T15:00:00Z'))
  await page.goto('./')
  await expect(page.locator('.featured-park h2')).toHaveText('Magic Kingdom')
  await expect(page.locator('.featured-park .resort-label')).toHaveText('Walt Disney World Resort')
  await expect(page.locator('.featured-step-count')).toContainText('15 etapas no progresso')
  await expect(page.locator('.upcoming-park').filter({ hasText: 'Magic Kingdom' })).toHaveCount(0)
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(page.locator('body')).toHaveJSProperty('scrollWidth', width)
    await page.locator('.featured-park').scrollIntoViewIfNeeded()
    await page.screenshot({ path: `test-results/featured-magic-${width}.png` })
  }
  await page.setViewportSize({ width: 390, height: 900 })
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('link', { name: 'Roteiro', exact: true }).click()
  await expect(page.getByTestId('step-big-thunder')).toBeAttached()
})
